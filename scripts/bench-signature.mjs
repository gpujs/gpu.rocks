/**
 * scripts/bench-signature.mjs — GENERATES src/Bench/signature.js from a run.
 *
 * Brief mode used to show ten hand-picked rows, one per distinct thing a GPU is
 * good or bad at. That list was a judgement, and judgements go stale: a row
 * picked because the GPU lost at it stays on the list after the backend gets
 * faster, and a row that became spectacular never gets promoted.
 *
 * So the list is derived now. Brief mode shows the ten most flattering results
 * in the newest saved run — nothing is exempt, nothing is protected, and the
 * list changes when the numbers change. Re-run this after every recording:
 *
 *   node scripts/bench-record.mjs --label "…"   # measure
 *   node scripts/bench-signature.mjs            # re-derive brief mode
 *
 * FLATTERING MEANS VIA gpu.js. The ranking uses the best of the three gpu.js
 * GPU columns against the plain-JS baseline, not the hand-written WebGPU
 * column. The bare column exists to price the runtime — it is the number that
 * says what gpu.js costs you — so ranking by it would fill brief mode with rows
 * chosen for how well the library was AVOIDED.
 *
 * matmul is pinned to the top wherever it lands in the ranking. It is the case
 * every GPU claim starts from and the one a reader already has an intuition
 * for, so it anchors the rows under it. That is the only fixed thing here.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SAVED = join(ROOT, 'src/Bench/saved');
const OUT = join(ROOT, 'src/Bench/signature.js');

const argv = process.argv.slice(2);
const arg = n => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
const TOP = Number(arg('--top') || 10);
const PIN = arg('--pin') || 'matmul';
// A row whose columns error still has a valid number in the columns that ran,
// so it can rank. Off by default because brief mode is the first thing a
// visitor sees; --skip-broken keeps error cells out of it.
const skipBroken = argv.includes('--skip-broken');

const files = readdirSync(SAVED).filter(f => f.endsWith('.json')).sort().reverse();
const wanted = arg('--run');
const file = wanted ? files.find(f => f.includes(wanted)) : files[0];
if (!file) {
  console.error('bench-signature: no saved run to derive from');
  process.exit(1);
}
const run = JSON.parse(readFileSync(join(SAVED, file), 'utf8'));
const { default: workloads } = await import(`${ROOT}/src/Bench/workloads/index.js`);
const meta = new Map(workloads.map(w => [w.id, w]));

const BASELINE = 'bare-js';
const GPUJS = ['webgpu', 'webgl2', 'webgl'];

const ranked = [];
for (const [id, cells] of Object.entries(run.results)) {
  if (!meta.has(id)) continue; // in the run, no longer in the registry
  const base = cells[BASELINE];
  if (!base || typeof base.ms !== 'number' || base.ms <= 0) continue;

  const broken = Object.entries(cells)
    .filter(([, c]) => c && (c.wrong || c.error))
    .map(([col]) => col);
  if (skipBroken && broken.length) continue;

  let best = null;
  for (const col of GPUJS) {
    const c = cells[col];
    if (!c || typeof c.ms !== 'number' || c.ms <= 0 || c.wrong || c.error) continue;
    const factor = base.ms / c.ms;
    if (!best || factor > best.factor) best = { col, factor };
  }
  if (!best) continue;
  ranked.push({ id, name: (meta.get(id) || {}).name || id, ...best, broken });
}

ranked.sort((a, b) => b.factor - a.factor);
const top = ranked.slice(0, TOP);

// Pin without changing the membership: if the pinned row earned a place it
// simply moves to the front; if it did not, it takes the last slot rather than
// growing the list past TOP.
const pinned = top.find(r => r.id === PIN) || ranked.find(r => r.id === PIN);
let list = top;
if (pinned) {
  list = [pinned, ...top.filter(r => r.id !== PIN)].slice(0, TOP);
}

const round = x => (x >= 100 ? x.toFixed(0) : x.toFixed(1));
const body = list
  .map(r => `  ['${r.id}', '${round(r.factor)}x on ${r.col}'],`)
  .join('\n');

writeFileSync(OUT, `/**
 * src/Bench/signature.js — GENERATED by scripts/bench-signature.mjs.
 *
 * The ten rows brief mode runs: the most flattering results in the newest saved
 * run, measured as the best gpu.js GPU column against the plain-JS baseline.
 * Nothing is hand-picked and nothing is protected — re-record, re-run the
 * generator, and the list follows the numbers.
 *
 * matmul is pinned first. Every GPU claim starts there and a reader already has
 * an intuition for it, so it anchors the rows below it.
 *
 * Derived from: ${run.label} · ${run.machine} · gpu.js ${run.gpujs} (${run.date})
 *
 * Never hand-edited. To change what brief mode shows, change what the numbers
 * say — or the rule in the generator.
 */
const SIGNATURE = [
${body}
];

export const SIGNATURE_IDS = SIGNATURE.map(([id]) => id);
export const SIGNATURE_WHY = new Map(SIGNATURE);
export default SIGNATURE_IDS;
`);

console.log(`bench-signature: derived from ${file}`);
console.log(`  rank  row                     best gpu.js column        broken`);
for (const [i, r] of list.entries()) {
  console.log(
    `  ${String(i + 1).padStart(4)}  ${r.id.padEnd(22)} ${`${round(r.factor)}x`.padStart(8)} on ${r.col.padEnd(8)}` +
    `${r.broken.length ? `  ${r.broken.join(', ')}` : ''}`
  );
}
const dropped = ranked.slice(TOP).filter(r => !list.some(l => l.id === r.id));
if (dropped.length) {
  console.log(`\n  just missed: ${dropped.slice(0, 5).map(r => `${r.id} (${round(r.factor)}x)`).join(', ')}`);
}
